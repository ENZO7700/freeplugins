const SidebarMenuButton = React.forwardRef<
  HTMLButtonElement,
  React.ButtonHTMLAttributes<HTMLButtonElement> & {
    asChild?: boolean
    isActive?: boolean
    tooltip?: string | React.ComponentProps<typeof TooltipContent>
  } & VariantProps<typeof sidebarMenuButtonVariants>
>(
  (
    {
      asChild = false,
      isActive = false,
      size = "default",
      tooltip,
      className,
      children,
      ...props
    },
    ref
  ) => {
    const Comp = asChild ? Slot : "button"
    const { isMobile, state } = useSidebar()

    const buttonContent = (
      <>
        {React.Children.map(children, (child, index) => {
          if (React.isValidElement(child) && typeof child.type !== 'string' && child.type.displayName?.includes("Chevron")) {
            return React.cloneElement(child, {
              className: cn(child.props.className, 'transition-opacity duration-300', state === 'collapsed' ? 'opacity-0' : 'opacity-100')
            });
          }
          if (React.isValidElement(child) && child.type === 'span') {
             return React.cloneElement(child, {
              className: cn(child.props.className, 'transition-opacity duration-200 whitespace-nowrap', state === 'collapsed' ? 'opacity-0' : 'opacity-100')
            });
          }
           if (React.isValidElement(child)) {
             return child
           }
          return null
        })}
      </>
    );

    const button = (
      <Comp
        ref={ref}
        data-sidebar="menu-button"
        data-size={size}
        data-active={isActive}
        className={cn(
            sidebarMenuButtonVariants({ size }), 
            state === 'collapsed' && 'justify-center',
            className
        )}
        {...props}
      >
        {buttonContent}
      </Comp>
    )

    if (state === 'expanded' && !isMobile) {
        return button;
    }

    if (!tooltip) {
      return button
    }
    
    if (typeof tooltip === "string") {
      tooltip = {
        children: tooltip,
      }
    }

    return (
      <Tooltip>
        <TooltipTrigger asChild>{button}</TooltipTrigger>
        <TooltipContent
          side="right"
          align="center"
          {...tooltip}
        />
      </Tooltip>
    )
  }
)
SidebarMenuButton.displayName = "SidebarMenuButton"


